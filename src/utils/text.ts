// Data in this app arrives however a rep typed it (or however a CSV import
// had it) — contact names, companies, locations, etc. often come back
// all-lowercase or all-caps. This normalizes display without touching the
// underlying value (email addresses and tag names are case-sensitive/
// meaningful as-is, so callers should skip those).
export function toTitleCase(value?: string | null): string {
  if (!value) return '';
  return value
    .toLowerCase()
    .split(' ')
    .map((word) => (word ? word[0].toUpperCase() + word.slice(1) : word))
    .join(' ');
}

// Reps enter phone numbers however they come in (with/without country code,
// dashes, spaces) — normalize to a consistent display format without
// touching the stored value. Falls back to the raw string for anything that
// doesn't look like a standard 10/11-digit number (international numbers
// with unusual lengths, extensions, etc.).
export function formatPhone(value?: string | null): string {
  if (!value) return '';
  const digits = value.replace(/\D/g, '');
  if (digits.length === 10) {
    return `(${digits.slice(0, 3)}) ${digits.slice(3, 6)}-${digits.slice(6)}`;
  }
  if (digits.length === 11 && digits[0] === '1') {
    return `+1 (${digits.slice(1, 4)}) ${digits.slice(4, 7)}-${digits.slice(7)}`;
  }
  if (digits.length > 11) {
    return `+${digits}`;
  }
  return value;
}

// system_audit entries generated by the update-companies workflow read
// "actor updated Company: free-text reason" — the actor/company segments
// come from however the name was typed (see toTitleCase above), but the
// reason after the colon is the user's own words and must stay verbatim.
// Rows written before the backend started title-casing those segments
// itself still need this fixed up at render time, since the summary text
// is stored as-is in the database rather than recomputed on read.
export function humanizeAuditSummary(summary: string): string {
  const m = summary.match(/^(.+?) updated (.+?): (.+)$/);
  if (!m) return summary;
  const [, actor, obj, reason] = m;
  return `${toTitleCase(actor)} updated ${toTitleCase(obj)}: ${reason}`;
}

export function formatRelativeTime(iso: string): string {
  const diffMs = Date.now() - new Date(iso).getTime();
  const mins = Math.floor(diffMs / 60000);
  if (mins < 1) return 'Just now';
  if (mins < 60) return `${mins}m ago`;
  const hours = Math.floor(mins / 60);
  if (hours < 24) return `${hours}h ago`;
  const days = Math.floor(hours / 24);
  if (days === 1) return 'Yesterday';
  if (days < 30) return `${days}d ago`;
  return new Date(iso).toLocaleDateString(undefined, { month: 'short', day: 'numeric' });
}
